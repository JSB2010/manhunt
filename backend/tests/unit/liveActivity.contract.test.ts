import { readFileSync, writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { decideClaim, requestPause, startRound, submitClaim } from '../../src/domain/engine.js';
import { tickRound } from '../../src/domain/tick.js';
import type { CaptureClaim, GpsPoint, RoundDoc, SessionDoc } from '../../src/domain/types.js';
import { liveActivityAttributes, liveActivityStaleDate, liveActivityState, renderView, type LiveActivityAttributes, type LiveActivityState, type ViewDoc } from '../../src/domain/views.js';
import { allPhones, claim, HIDER, members, MIN, point, readyRound, SEEKER, SEEKER_C, T0 } from './fixtures.js';

/**
 * Contract between the server's Live Activity renderer (ActivityKit pushes) and the
 * app's (`RoundActivityContent.swift`, local updates): both map the same sanitized
 * view to the same content state. The cases are written to
 * shared/fixtures/live-activity.json, which ManhuntCrewsTests decodes and checks
 * against the Swift mapping. Regenerate with UPDATE_FIXTURES=1 after changing either.
 */
const FIXTURE = new URL('../../../shared/fixtures/live-activity.json', import.meta.url);

interface Case {
  name: string;
  clockOffsetMs: number;
  view: ViewDoc;
  attributes: LiveActivityAttributes | null;
  state: LiveActivityState | null;
  staleDate: number | null;
}

const tick = (r: RoundDoc, now: number, samples: GpsPoint[]) =>
  tickRound(r, now, { hiderSamples: async (from, to) => samples.filter((x) => x.recordedAt >= from && x.recordedAt <= to), activeClaim: null });

function walk(until: number): GpsPoint[] {
  const pts: GpsPoint[] = [];
  for (let t = T0, i = 0; t <= until; t += 7_000, i++) pts.push(point({ pointId: `w${i}`, recordedAt: t, receivedAt: t + 2_000, latitude: 39.7 + i * 1e-4, longitude: -105.1 }));
  return pts;
}

async function cases(): Promise<Case[]> {
  const out: Case[] = [];
  const add = (name: string, uid: string, session: SessionDoc, round: RoundDoc, now: number, activeClaim: CaptureClaim | null = null, clockOffsetMs = 0) => {
    const view = renderView({ uid, session, round, members: members(session), activeClaim, now });
    // The stored view carries its hash; it doesn't matter to the mapping.
    const state = view.round ? liveActivityState(view.round, clockOffsetMs) : null;
    out.push({ name, clockOffsetMs, view, attributes: liveActivityAttributes(view), state, staleDate: state ? liveActivityStaleDate(state) : null });
  };

  const { session: s, round: ready } = readyRound({ maxChaseSeconds: 3600 }, { three: true, seekMode: 'RACE' });
  add('ready check: no Live Activity yet', HIDER, s, ready, T0 - 10_000);
  const started = startRound(ready, s, HIDER, allPhones(s), [], T0).round;
  add('hider, head start running', HIDER, s, started, T0 + MIN);
  add('seeker, head start running, phone clock 2.5 s ahead', SEEKER, s, started, T0 + MIN, null, 2_500);
  const hsPaused = requestPause(started, SEEKER, 'SAFETY', 'Someone fell', T0 + 4 * MIN).round;
  add('seeker, safety pause in the head start', SEEKER, s, hsPaused, T0 + 5 * MIN);

  const track = walk(T0 + 40 * MIN);
  let chase = (await tick(started, T0 + 10 * MIN, track)).round;
  chase = (await tick(chase, T0 + 20 * MIN, track)).round;
  add('seeker, chase with two pings out', SEEKER, s, chase, T0 + 21 * MIN);
  add('hider, chase', HIDER, s, chase, T0 + 21 * MIN, null, -1_250);

  const waiting = (await tick(chase, T0 + 30 * MIN, track.filter((p) => p.recordedAt < T0 + 25 * MIN))).round;
  add('hider, ping waiting on a fix', HIDER, s, waiting, T0 + 30 * MIN + 5_000);

  const c = claim({ seekerUid: SEEKER_C, seekerTeam: 'C', status: 'PENDING', submittedAt: T0 + 22 * MIN, officialChaseMsAtClaim: 12 * MIN });
  const pending = submitClaim(chase, claim({ seekerUid: SEEKER_C, seekerTeam: 'C' }), SEEKER_C, T0 + 22 * MIN).round;
  add('hider, catch claim to review', HIDER, s, pending, T0 + 22 * MIN + 10_000, c);
  add('claiming seeker crew, claim under review', SEEKER_C, s, pending, T0 + 22 * MIN + 10_000, c);
  add('other seeking crew, claim under review', SEEKER, s, pending, T0 + 22 * MIN + 10_000, c);

  const caught = decideClaim(pending, c, HIDER, 'CONFIRM', null, T0 + 23 * MIN).round;
  add('hider, round over: caught', HIDER, s, caught, T0 + 23 * MIN);
  add('seeker, round over: caught by the other crew', SEEKER, s, caught, T0 + 23 * MIN);
  return out;
}

describe('Live Activity content contract (server ↔ app)', () => {
  it('matches shared/fixtures/live-activity.json', async () => {
    const actual = await cases();
    if (process.env.UPDATE_FIXTURES) {
      writeFileSync(FIXTURE, JSON.stringify({ about: 'Generated by backend/tests/unit/liveActivity.contract.test.ts (UPDATE_FIXTURES=1). Checked by ManhuntCrewsTests.', cases: actual }, null, 2) + '\n');
    }
    const stored = JSON.parse(readFileSync(FIXTURE, 'utf8')) as { cases: Case[] };
    expect(JSON.parse(JSON.stringify(actual))).toEqual(stored.cases);
  });

  it('maps each phase the way the Lock Screen needs it', async () => {
    const byName = Object.fromEntries((await cases()).map((c) => [c.name, c]));
    const sec = (ms: number) => ms / 1000;

    expect(byName['ready check: no Live Activity yet']!.state).toBeNull();
    expect(byName['ready check: no Live Activity yet']!.attributes).toBeNull();

    const hs = byName['hider, head start running']!;
    expect(hs.attributes).toEqual({ sessionId: 'sess1', roundId: 'round1', roundIndex: 1, role: 'HIDING', crew: 'A', crewName: 'Blue crew' });
    // The Lock Screen names the crew by its colour, never its people (ADR 0019).
    expect(JSON.stringify(Object.values(byName).map((c) => c.attributes))).not.toMatch(/Crew A|Crew B|Crew C/);
    expect(hs.state).toMatchObject({ phase: 'HEAD_START', headStartEndsAt: sec(T0 + 10 * MIN), chaseStartedAt: null, chaseElapsed: null, nextPingAt: null, lastPing: null });
    // The phone's clock offset shifts every displayed time so the system's own timers read server time.
    expect(byName['seeker, head start running, phone clock 2.5 s ahead']!.state!.headStartEndsAt).toBe(sec(T0 + 10 * MIN + 2_500));

    expect(byName['seeker, safety pause in the head start']!.state).toMatchObject({ phase: 'PAUSED', pausedPhase: 'HEAD_START', safetyPause: true, headStartRemaining: 360, headStartEndsAt: null });

    expect(byName['seeker, chase with two pings out']!.state).toMatchObject({
      phase: 'CHASE',
      chaseStartedAt: sec(T0 + 10 * MIN),
      chaseElapsed: null,
      nextPingAt: sec(T0 + 30 * MIN),
      nextPingIndex: 2,
      timeCapAt: sec(T0 + 70 * MIN),
      lastPing: { index: 1, at: sec(T0 + 20 * MIN), missing: false },
      pingWaiting: false,
    });
    expect(byName['hider, chase']!.state!.chaseStartedAt).toBe(sec(T0 + 10 * MIN - 1_250));
    expect(byName['hider, ping waiting on a fix']!.state).toMatchObject({ phase: 'CHASE', pingWaiting: true, lastPing: { index: 1 } });

    for (const n of ['hider, catch claim to review', 'claiming seeker crew, claim under review']) {
      expect(byName[n]!.state).toMatchObject({ phase: 'CAPTURE_PENDING', chaseElapsed: 720, chaseStartedAt: null, claim: { crew: 'C', expiresAt: sec(T0 + 24 * MIN) } });
    }
    expect(byName['other seeking crew, claim under review']!.state!.claim).toEqual({ crew: 'C', expiresAt: null });

    expect(byName['hider, round over: caught']!.state).toMatchObject({ phase: 'ENDED', chaseElapsed: 720, outcome: { result: 'CAUGHT', creditCrews: ['C'] }, claim: null, pingWaiting: false });
    expect(byName['seeker, round over: caught by the other crew']!.state!.outcome).toEqual({ result: 'CAUGHT', creditCrews: ['C'] });

    // Stale a little after the next expected update; never while nothing is due.
    expect(hs.staleDate).toBe(sec(T0 + 10 * MIN) + 90);
    expect(byName['seeker, chase with two pings out']!.staleDate).toBe(sec(T0 + 30 * MIN) + 90);
    expect(byName['hider, catch claim to review']!.staleDate).toBe(sec(T0 + 24 * MIN) + 90);
    expect(byName['other seeking crew, claim under review']!.staleDate).toBeNull();
    for (const n of ['seeker, safety pause in the head start', 'hider, ping waiting on a fix', 'hider, round over: caught']) expect(byName[n]!.staleDate, n).toBeNull();
  });
});
